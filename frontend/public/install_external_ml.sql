-- =============================================================================
-- MATERIALIZED RESULTS TABLE + refresh procedure.
--
-- IMPORTANT PLATFORM FINDING (confirmed against a real account): a Native
-- App's `reference()` function cannot invoke a stored PROCEDURE at all --
-- `CALL reference('x')(:arg)` is a syntax error (CALL does not accept a
-- reference() expression as its target), and `SELECT * FROM
-- TABLE(reference('x')(:arg))` resolves but fails with "Unknown table
-- function" for a PROCEDURE-type reference. Only TABLE/VIEW-type references
-- support the documented `SELECT * FROM reference('x')` query pattern.
--
-- So instead of the app calling MODELS.run_detection() live on every scan
-- (which also risks timing out Trust Center's scanner callback budget --
-- detecting across 20 models took several minutes in testing), this table
-- holds the LATEST detection run's raw rows, refreshed on a schedule below.
-- The app's reference points at this TABLE, not at the procedure.
-- =============================================================================

CREATE TABLE IF NOT EXISTS MODELS.detection_results (
  model_name VARCHAR, series VARCHAR, ts TIMESTAMP_NTZ, y FLOAT, forecast FLOAT,
  lower_bound FLOAT, upper_bound FLOAT, is_anomaly BOOLEAN, percentile FLOAT, distance FLOAT
);

CREATE OR REPLACE PROCEDURE MODELS.refresh_detection_results(run_id VARCHAR)
  RETURNS STRING
  LANGUAGE SQL
AS
$$
DECLARE
  det_res RESULTSET;
  row_count INT DEFAULT 0;
BEGIN
  det_res := (CALL MODELS.run_detection(:run_id));
  CREATE OR REPLACE TABLE MODELS.detection_results AS SELECT * FROM TABLE(det_res);
  row_count := (SELECT COUNT(*) FROM MODELS.detection_results);
  RETURN 'Refreshed detection_results: ' || row_count || ' rows.';
END;
$$;

-- =============================================================================
-- Weekly retraining task -- lives here (plain schema in a regular database),
-- not inside the app. Native Apps also cannot host TASK objects in a
-- versioned schema (confirmed separately), so keeping this external avoids
-- that constraint entirely in addition to the Class-object constraint.
-- Re-runs train_all_models(), which re-attempts any previously-skipped
-- signals in case the account now has matching activity.
-- =============================================================================

CREATE OR REPLACE TASK MODELS.ml_anomaly_retrain_task
  SCHEDULE = 'USING CRON 0 2 * * 0 UTC'
  COMMENT = 'Weekly retraining of all 20 ML anomaly detection models'
AS
CALL MODELS.train_all_models();

ALTER TASK MODELS.ml_anomaly_retrain_task RESUME;

-- Detection-refresh task: keeps MODELS.detection_results current for the app
-- to read via its TABLE reference, independent of the weekly retrain cadence.
CREATE OR REPLACE TASK MODELS.ml_anomaly_detect_task
  SCHEDULE = 'USING CRON 0 */6 * * * UTC'
  COMMENT = 'Refreshes detection_results every 6 hours for the Native App to read'
AS
CALL MODELS.refresh_detection_results(UUID_STRING());

ALTER TASK MODELS.ml_anomaly_detect_task RESUME;

-- Run the initial training now (also re-runnable any time by hand):
CALL MODELS.train_all_models();

-- Populate detection_results immediately so the app has data as soon as the
-- reference is bound, instead of waiting up to 6 hours for the first task run:
CALL MODELS.refresh_detection_results(UUID_STRING());
