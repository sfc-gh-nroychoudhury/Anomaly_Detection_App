-- =============================================================================
-- install_external_ml.sql
--
-- ONE-TIME, MANUAL install step. Run this once, as ACCOUNTADMIN (or any role
-- with IMPORTED PRIVILEGES ON SNOWFLAKE DB), in the SAME account where the
-- "ML Behavioral Anomaly Detection" Native App is installed.
--
-- WHY THIS EXISTS (do not skip this step, and do not try to move this logic
-- into the app): SNOWFLAKE.ML.ANOMALY_DETECTION objects are "Class" objects,
-- and Snowflake's Native App Framework does not support creating Class
-- objects inside an application's own database ("Classes are not supported
-- in an application" -- confirmed empirically against a real account, not
-- assumed). This is the ONLY part of the whole system that cannot live
-- inside the Native App. Everything else -- correlation/scoring, Cortex AI
-- narratives, the Trust Center scanner callback, the dashboard UI -- lives
-- entirely inside the app and requires zero manual SQL.
--
-- This script is intentionally minimal: it creates ONLY the 20 ML models,
-- ONE wrapper procedure the app calls via a Native App reference, and the
-- weekly retrain task. There are no separate view objects -- each model's
-- training query and each detection call use an inline subquery, since
-- nothing else ever needs to query these views by name.
--
-- Every model is trained inside a per-model error-tolerant block: some
-- signals (e.g. AD_ROWS_UNLOADED, AD_OUTBOUND_TRANSFER) may have zero
-- matching rows over the last 90 days on quiet accounts or accounts that
-- don't use that particular feature -- that is expected and NOT a failure.
-- MODELS.train_all_models() reports exactly how many models trained vs.
-- were skipped, and the weekly retrain task re-attempts skipped signals
-- automatically once real activity shows up.
--
-- After running this script, go to the app's Setup page and complete the
-- final step: binding the app's reference to MODELS.RUN_DETECTION. See
-- README.md in this directory for the exact command.
-- =============================================================================

CREATE DATABASE IF NOT EXISTS ML_ANOMALY_EXTERNAL;
CREATE SCHEMA IF NOT EXISTS ML_ANOMALY_EXTERNAL.MODELS;
USE SCHEMA ML_ANOMALY_EXTERNAL.MODELS;

